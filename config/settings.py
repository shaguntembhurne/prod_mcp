# ---------------------------------------------------------------------------
# Database
# ---------------------------------------------------------------------------
# Defaults to SQLite for local development.
# To use PostgreSQL set DATABASE_URL=postgres://user:pass@host:5432/dbname in .env

DATABASE_URL = config("DATABASE_URL", default="")

if DATABASE_URL:
    import re

    _m = re.match(
        r"postgres://(?P<user>[^:]+):(?P<password>[^@]+)@(?P<host>[^:]+):(?P<port>\d+)/(?P<name>.+)",
        DATABASE_URL,
    )
    if _m:
        DATABASES = {
            "default": {
                "ENGINE": "django.db.backends.postgresql",
                "NAME": _m.group("name"),
                "USER": _m.group("user"),
                "PASSWORD": _m.group("password"),
                "HOST": _m.group("host"),
                "PORT": _m.group("port"),
            }
        }
    else:
        raise ValueError(f"Cannot parse DATABASE_URL: {DATABASE_URL}")
else:
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }
    }

